# 5. LOAD DATA AND PREDICT RISK
# ---------------------------------------------------------
df_lines, df_subs = load_utility_data()
model = train_risk_model(df_lines)

features = [
    "distance_to_conductor_m",
    "tree_height_m",
    "growth_rate_cm_yr",
    "soil_moisture_pct",
    "voltage_kv"
]

# Predict probability of the synthetic high-risk class.
df_lines["risk_score"] = model.predict_proba(
    df_lines[features]
)[:, 1]

df_lines["risk_ranking"] = (
    df_lines["risk_score"]
    .rank(ascending=False, method="first")
    .astype(int)
)

# Status is derived from model risk, not measured grid status.
df_lines["status"] = np.where(
    df_lines["risk_score"] >= 0.7,
    "High Risk",
    "Normal"
)


