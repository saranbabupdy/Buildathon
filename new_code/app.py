# 2. LOAD DATA FROM THE FIRST CODE
# ---------------------------------------------------------
@st.cache_data
def load_utility_data():
    required_files = [
        "transmission_lines.csv",
        "vegetation_lidar_satellite.csv",
        "substations.csv"
    ]

    # Generate datasets only if one or more files are missing.
    if not all((APP_DIR / file).exists() for file in required_files):
        generate_csvs()

    # Load the three CSV files generated by data_generator.py.
    df_lines = pd.read_csv(APP_DIR / "transmission_lines.csv")
    df_veg = pd.read_csv(
        APP_DIR / "vegetation_lidar_satellite.csv"
    )
    df_subs = pd.read_csv(APP_DIR / "substations.csv")

    # Match each transmission line with its vegetation metrics.
    df_lines = df_lines.merge(
        df_veg,
        on="line_id",
        how="left",
        validate="one_to_one"
    )

    # Validate that every transmission line has vegetation data.
    vegetation_columns = [
        "distance_to_conductor_m",
        "tree_height_m",
        "growth_rate_cm_yr",
        "soil_moisture_pct"
    ]

    if df_lines[vegetation_columns].isnull().any().any():
        raise ValueError(
            "Some transmission lines are missing vegetation data. "
            "Check the line_id values in both CSV files."
        )

    # The original line dataset has no operational status column.
    # Initialize it; the risk model assigns a status after prediction.
    df_lines["status"] = "Normal"

    return df_lines, df_subs


