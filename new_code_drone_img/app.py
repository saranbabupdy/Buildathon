# 5. DRONE IMAGE MODEL (trained by train_drone_model.py)
# ---------------------------------------------------------
@st.cache_resource
def get_drone_bundle(_mtime):
    # _mtime only exists so the cache refreshes after retraining.
    return load_bundle()


@st.cache_data(show_spinner=False)
def classify_image(data: bytes, _mtime):
    """Classify one uploaded image; cached per file content."""
    import io
    img = Image.open(io.BytesIO(data)).convert("RGB")
    probs = predict_proba(get_drone_bundle(_mtime), img)
    return probs, image_risk(probs)


def bundle_mtime():
    return BUNDLE_PATH.stat().st_mtime if BUNDLE_PATH.exists() else 0.0


