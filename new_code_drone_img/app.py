# 4. DISASTER ISOLATION & BACKUP RESTORATION PLANNER
# ---------------------------------------------------------
def run_disaster_isolation_and_backup(
    df_lines,
    df_subs,
    disaster_active
):
    # MultiGraph preserves multiple transmission lines
    # connecting the same pair of substations.
    G = nx.MultiGraph()

    # Add substations as network nodes.
    for _, sub in df_subs.iterrows():
        G.add_node(
            sub["substation_id"],
            type="substation",
            status=sub["status"],
            capacity=sub["available_capacity_mw"]
        )

    # Use reproducible assignments for simulated connections.
    rng = np.random.default_rng(42)
    sub_ids = df_subs["substation_id"].tolist()

    # Add each transmission line as a separate network edge.
    for _, line in df_lines.iterrows():
        u = line["substation_id"]

        # Prefer the associated substation as the source.
        # Select a different substation as the destination.
        alternatives = [sid for sid in sub_ids if sid != u]

        if not alternatives:
            continue

        v = rng.choice(alternatives)

        line_status = (
            "Isolated"
            if (
                disaster_active
                and line["risk_score"] > 0.7
            )
            else "Live"
        )

        G.add_edge(
            u,
            v,
            key=line["line_id"],
            line_id=line["line_id"],
            weight=line["distance_to_conductor_m"],
            status=line_status,
            voltage=line["voltage_kv"]
        )

    isolated_lines = []
    backup_plan = []

    # Inspect every individual line, including parallel edges.
    for u, v, key, data in G.edges(keys=True, data=True):
        if data["status"] == "Isolated":
            isolated_lines.append(data["line_id"])

            backup_plan.append({
                "Isolated_Line": data["line_id"],
                "Action": (
                    "Reroute power load through "
                    "secondary microgrid tie"
                ),
                "Alternate_Node": v,
                "Status": "Standby Ready"
            })

    return isolated_lines, pd.DataFrame(backup_plan)


